// คืน genre prompt ของโปรเจกต์ — เรียงลำดับ: override ใน settings > customGenrePrompt > default
export function genrePrompt(project, settings) {
  const g = project?.genre || 'fantasy';
  const override = settings?.genrePrompts?.[g];
  if (override?.trim()) return override.trim();
  if (g === 'custom') return (project?.customGenrePrompt || '').trim();
  return GENRES[g]?.prompt || '';
}

export function genreLabel(g) {
  const it = GENRES[g];
  return it ? `${it.icon} ${it.label}` : g || '-';
}
